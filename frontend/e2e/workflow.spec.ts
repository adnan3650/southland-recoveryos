import {test,expect} from '@playwright/test'
test('resident intake, evidence, readiness, resources, tasks, packet and resumption',async({page},info)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/');await page.getByRole('link',{name:'Start your recovery',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Your safety comes first.'})).toBeVisible()
 await page.getByRole('link',{name:'I understand — create my case'}).click()
 await page.getByLabel('Resident name').fill('Alex Morgan')
 await page.getByLabel('Incident date').fill('2026-09-12')
 await page.getByLabel('What happened?').fill('Fictional basement flooding damaged a sofa and stored belongings. Synthetic demonstration only.')
 await page.getByLabel('Property situation').selectOption('owner')
 await page.getByRole('button',{name:'Create recovery case'}).click()
 await expect(page.getByRole('heading',{name:'A little clarity, Alex.'})).toBeVisible()
 const caseUrl=page.url()
 async function nav(name:string){if(info.project.name==='mobile')await page.getByRole('button',{name:'Open navigation'}).click();await page.getByRole('navigation',{name:'Recovery navigation'}).getByRole('link',{name,exact:true}).click()}
 await nav('Damage & evidence')
 await page.getByLabel('Choose evidence file').setInputFiles({name:'synthetic-estimate.txt',mimeType:'text/plain',buffer:Buffer.from('SYNTHETIC estimate for damaged belongings. Contractor verification required.')})
 await page.getByLabel('Document category').selectOption('estimate')
 await page.getByRole('button',{name:'Save evidence'}).click()
 await expect(page.getByRole('heading',{name:'synthetic-estimate.txt'})).toBeVisible()
 await page.getByLabel('Item or affected area').fill('Basement sofa')
 await page.getByLabel('Location in property').fill('Basement')
 await page.getByLabel('What did you observe?').fill('Wet upholstery; fictional resident observation.')
 await page.getByRole('button',{name:'Save observation'}).click()
 await expect(page.getByRole('heading',{name:'Basement sofa',exact:true})).toBeVisible()
 await nav('Insurance preparation')
 await page.getByLabel('Insurer',{exact:true}).fill('Synthetic Insurer')
 await page.getByRole('button',{name:'Save insurance record'}).click()
 await expect(page.getByRole('status')).toContainText('Insurance information saved.')
 await page.getByLabel('Organization or contact').fill('Synthetic Insurer')
 await page.getByLabel('What did you discuss?').fill('Asked about policy wording and required evidence.')
 await page.getByRole('button',{name:'Save contact note'}).click()
 await expect(page.getByRole('heading',{name:'Synthetic Insurer',exact:true})).toBeVisible()
 await nav('Assistance programs')
 await expect(page.getByText('Potentially relevant',{exact:true})).toBeVisible()
 await expect(page.getByText('Current availability unverified',{exact:true}).first()).toBeVisible()
 await nav('Immediate assistance')
 await page.getByRole('textbox',{name:'Search resources'}).fill('food')
 await expect(page.getByRole('heading',{name:'Greater Chicago Food Depository'})).toBeVisible()
 await nav('Recovery assistant')
 await expect(page.getByRole('button',{name:'Ask recovery assistant'})).toBeDisabled()
 const health=await (await page.request.get('/api/health')).json()
 if(!health.ai_configured)await expect(page.getByText('Live Claude is awaiting server configuration.')).toBeVisible()
 else await expect(page.getByText('Claude configured',{exact:true})).toBeVisible()
 await nav('Overview')
 await page.getByRole('button',{name:'Complete Confirm your immediate safety'}).click()
 await expect(page.getByRole('button',{name:'Reopen Confirm your immediate safety'})).toBeVisible()
 await page.getByRole('button',{name:'Add a task',exact:true}).click()
 await page.getByLabel('Task title').fill('Follow up with caseworker')
 await page.getByRole('button',{name:'Add task',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Follow up with caseworker'})).toBeVisible()
 await page.screenshot({path:info.outputPath('dashboard.png'),fullPage:true})
 await page.locator('.stat-task-button').click();await expect(page).toHaveURL(caseUrl)
 await nav('Recovery packet')
 const downloaded=page.waitForEvent('download');await page.getByRole('button',{name:'Download PDF packet'}).click();const file=await downloaded
 expect(file.suggestedFilename()).toBe('southland-recovery-packet.pdf')
 await page.reload();await expect(page.getByRole('heading',{name:'Your story. Ready to share.'})).toBeVisible()
 await page.goto('/#/cases');await page.getByRole('link',{name:/Alex Morgan’s recovery/}).click()
 await expect(page.getByRole('heading',{name:'Follow up with caseworker'})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 expect(errors).toEqual([])
})
