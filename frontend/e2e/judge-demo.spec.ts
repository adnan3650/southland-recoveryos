import {test,expect} from '@playwright/test'
test('judge fixture is saved once, readiness updates, and packet downloads',async({page},info)=>{
 await page.goto('/#/demo')
 await expect(page.getByRole('heading',{name:'One resident. One connected recovery journey.'})).toBeVisible()
 await page.getByRole('button',{name:'Prepare judge demo case'}).click()
 await expect(page.getByRole('status')).toContainText('Demo case prepared.')
 const caseId=await page.evaluate(()=>localStorage.getItem('southland_judge_demo_case'))
 expect(caseId).toBeTruthy()
 let data=await (await page.request.get('/api/cases/'+caseId)).json()
 expect(data.documents).toHaveLength(3)
 expect(data.damage_items).toHaveLength(2)
 expect(data.conversations).toHaveLength(0)
 expect(data.analyses).toHaveLength(0)
 expect((await (await page.request.get('/api/cases/'+caseId+'/readiness')).json()).percent).toBe(80)
 await page.getByRole('button',{name:'Check and finish demo setup'}).click()
 await expect(page.getByRole('status')).toContainText('Demo case prepared.')
 data=await (await page.request.get('/api/cases/'+caseId)).json()
 expect(data.documents).toHaveLength(3);expect(data.damage_items).toHaveLength(2)
 await page.getByRole('link',{name:'Open Alex’s workspace'}).click()
 await expect(page.getByRole('heading',{name:'A little clarity, Alex.'})).toBeVisible()
 const wordDownload = page.waitForEvent('download')
 await page.getByRole('button',{name:'Download Word checklist'}).click()
 expect((await wordDownload).suggestedFilename()).toBe('southland-recovery-checklist.docx')
 await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('Clipboard unavailable') } } }))
 await page.getByRole('button',{name:'Copy checklist',exact:true}).click()
 await expect(page.getByLabel('Checklist text')).toContainText('Recovery checklist')
 await expect(page.getByLabel('Checklist text')).toContainText('Synthetic demonstration case')
 if(info.project.name==='mobile')await page.getByRole('button',{name:'Open navigation'}).click()
 await page.getByRole('navigation',{name:'Recovery navigation'}).getByRole('link',{name:'Insurance preparation',exact:true}).click()
 await page.getByLabel('Organization or contact').fill('Synthetic Insurer')
 await page.getByLabel('What did you discuss?').fill('Fictional rehearsal: requested full policy and evidence checklist.')
 await page.getByRole('button',{name:'Save contact note'}).click()
 await expect(page.getByRole('status')).toContainText('Contact note saved.')
 expect((await (await page.request.get('/api/cases/'+caseId+'/readiness')).json()).percent).toBe(100)
 await page.goto('/#/case/'+caseId+'/report')
 const download=page.waitForEvent('download')
 await page.getByRole('button',{name:'Download PDF packet'}).click()
 expect((await download).suggestedFilename()).toBe('southland-recovery-packet.pdf')
 await page.goto('/#/demo')
 await expect(page.getByRole('link',{name:'Open Alex’s workspace'})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
