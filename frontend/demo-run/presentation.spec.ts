import {test,expect} from '@playwright/test'
import {mkdir} from 'node:fs/promises'
import {resolve} from 'node:path'

test('record genuine local prototype workflow without simulated AI',async({page})=>{
 page.setDefaultTimeout(10000)
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 const scene=async(ms=6000)=>{await page.evaluate(()=>window.scrollTo(0,0));await page.waitForTimeout(ms)}
 const nav=async(name:string)=>{console.log('Recording:',name);await page.getByRole('navigation',{name:'Recovery navigation'}).getByRole('link',{name,exact:true}).click();await scene()}
 await page.goto('/');await scene(5000)
 await page.getByRole('link',{name:'Open the judge demonstration'}).click();await scene(7000)
 await page.getByRole('button',{name:'Prepare judge demo case'}).click()
 await expect(page.getByRole('status')).toContainText('Demo case prepared.')
 const cid=await page.evaluate(()=>localStorage.getItem('southland_judge_demo_case'))
 await page.getByRole('link',{name:'Open Alex’s workspace'}).click();await scene(8000)
 await nav('Damage & evidence')
 const saved=await (await page.request.get('/api/cases/'+cid)).json()
 const photo=saved.documents.find((d:{name:string})=>d.name==='synthetic-basement-demo.png')
 await page.goto('/api/cases/'+cid+'/documents/'+photo.id+'/file');await page.waitForTimeout(6000)
 await page.goto('/#/case/'+cid+'/evidence');await page.getByRole('heading',{name:'Damage inventory',exact:true}).scrollIntoViewIfNeeded();await page.waitForTimeout(6000)
 await nav('Immediate assistance')
 await nav('Insurance preparation')
 await page.getByLabel('Organization or contact').fill('Synthetic Insurer')
 await page.getByLabel('Date contacted').fill('2026-11-06')
 await page.getByLabel('What did you discuss?').fill('Fictional rehearsal: requested full policy and evidence checklist.')
 await page.getByRole('button',{name:'Save contact note'}).click()
 await expect(page.getByRole('status')).toContainText('Contact note saved.')
 expect((await (await page.request.get('/api/cases/'+cid+'/readiness')).json()).percent).toBe(100)
 await scene(7000)
 await nav('Assistance programs')
 await nav('Recovery assistant')
 await expect(page.getByText('Live Claude is awaiting server configuration.')).toBeVisible()
 await nav('Overview')
 await page.getByRole('button',{name:'Complete Confirm your immediate safety'}).click()
 await expect(page.getByRole('button',{name:'Reopen Confirm your immediate safety'})).toBeVisible()
 await scene(5000)
 await nav('Recovery packet')
 const downloaded=page.waitForEvent('download')
 await page.getByRole('button',{name:'Download PDF packet'}).click()
 expect((await downloaded).suggestedFilename()).toBe('southland-recovery-packet.pdf')
 await scene(5000)
 await page.reload();await expect(page.getByRole('heading',{name:'Your story. Ready to share.'})).toBeVisible();await scene(4000)
 expect(errors).toEqual([])
 await page.screenshot({path:'../demo/recordings/packet-preview.png',fullPage:true})
 const video=page.video()!
 await page.close()
 await mkdir(resolve('../demo/recordings'),{recursive:true})
 await video.saveAs(resolve('../demo/recordings/prototype-walkthrough.webm'))
})
